#!/usr/bin/env python3
"""Generates the gridvis test map: a big flat sealed field under a sky ceiling,
with a tiled floor and some crates as landmarks, plus a hint grid so that the
open air is split into small leafs.

    makemap.py [out.map] [--size 4000] [--height 3072] [--grid 512] [--seed 1]

The monsters are not in the map: the mod spawns them (see mod/src/gridvis.qc).
The half size is stored in worldspawn as "gv_size" so the mod knows where to
spawn them.
"""
import argparse
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hintgrid import box_brush, hint_brushes  # noqa: E402

FLOOR_TEXTURES = ['ground1_6', 'wgrass1_1', 'ground1_2', 'rock3_8']
WALL = 'city2_1'
SKY = 'sky1'
TILE = 1024
WALL_THICK = 64


def make_map(size, height, grid, seed):
    rnd = random.Random(seed)
    s = size
    t = WALL_THICK
    brushes = []

    # floor: tiles with alternating textures, so panning is easy to see
    for ix, x in enumerate(range(-s, s, TILE)):
        for iy, y in enumerate(range(-s, s, TILE)):
            tex = FLOOR_TEXTURES[(ix + 2 * iy) % len(FLOOR_TEXTURES)]
            brushes.append(box_brush((x, y, -t), (min(x + TILE, s), min(y + TILE, s), 0), {'default': tex}))

    # walls and sky ceiling
    brushes.append(box_brush((-s - t, -s - t, -t), (-s, s + t, height), {'default': WALL}))
    brushes.append(box_brush((s, -s - t, -t), (s + t, s + t, height), {'default': WALL}))
    brushes.append(box_brush((-s, -s - t, -t), (s, -s, height), {'default': WALL}))
    brushes.append(box_brush((-s, s, -t), (s, s + t, height), {'default': WALL}))
    brushes.append(box_brush((-s - t, -s - t, height), (s + t, s + t, height + t), {'default': SKY}))

    # crates as landmarks: one per tile, at a random spot
    for x in range(-s, s, TILE):
        for y in range(-s, s, TILE):
            cx = x + rnd.randrange(128, TILE - 192)
            cy = y + rnd.randrange(128, TILE - 192)
            h = rnd.choice([64, 64, 128])
            brushes.append(box_brush((cx, cy, 0), (cx + 64, cy + 64, h), {'+z': 'crate0_top', 'default': 'crate0_side'}))

    # hint grid over the open air (inside the walls, floor to ceiling)
    hints = hint_brushes(((-s, -s, 0), (s, s, height)), grid) if grid > 0 else []

    world = [
        '// gridvis test map, generated by tools/makemap.py',
        '{',
        '"classname" "worldspawn"',
        '"wad" "gfx/quake101.wad"',
        '"message" "gridvis test field"',
        '"gv_size" "%d"' % size,
        '"_sunlight" "220"',
        '"_sun_mangle" "30 -60 0"',
        '"_sunlight2" "60"',
        '"_minlight" "40"',
    ]
    world += brushes + hints
    world.append('}')
    world += [
        '{',
        '"classname" "info_player_start"',
        '"origin" "0 0 24"',
        '"angle" "90"',
        '}',
    ]
    return '\n'.join(world) + '\n', len(brushes), len(hints)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('output', nargs='?', default=os.path.join(os.path.dirname(__file__), '..', 'testmap', 'gridtest.map'))
    ap.add_argument('--size', type=int, default=4000, help='half size of the field (default 4000)')
    ap.add_argument('--height', type=int, default=3072, help='height of the sky ceiling (default 3072)')
    ap.add_argument('--grid', type=int, default=512, help='hint grid spacing, 0 = no hint grid (default 512)')
    ap.add_argument('--seed', type=int, default=1)
    args = ap.parse_args()

    text, nbrushes, nhints = make_map(args.size, args.height, args.grid, args.seed)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, 'w', encoding='latin-1', newline='\n') as f:
        f.write(text)
    print('[makemap] %d brushes + %d hint brushes -> %s' % (nbrushes, nhints, os.path.normpath(args.output)))


if __name__ == '__main__':
    sys.exit(main())
